#!/usr/bin/env python3
"""Check the crate's ABI constants against the generated manifests.

The constants in `src/lib.rs` are hand-written; the manifests are generated by
`cyw43_iso`. This rejects drift between them. Run with no arguments.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
source = (ROOT / "src/lib.rs").read_text()


def constant(name, radix=0):
    match = re.search(rf"pub const {name}: [^=]+ =\s*([^;]+);", source, re.S)
    assert match, f"{name} missing from src/lib.rs"
    value = match[1].strip().strip('"').replace("_", "")
    return int(value, radix) if radix else value


def manifest(image):
    return json.loads((ROOT / "blobs" / image / "manifest.json").read_text())


failures = []


def check(label, actual, expected):
    if actual != expected:
        failures.append(f"{label}: crate {actual!r} != manifest {expected!r}")


stream = manifest("rx-stream")
check("CONTROLLER", constant("CONTROLLER"), stream["controller"])
check("FIRMWARE", constant("FIRMWARE"), stream["firmware"])
check("ROM_SHA256", constant("ROM_SHA256"), stream["rom_sha256"])
check("BOOT_FIRMWARE_SHA256", constant("BOOT_FIRMWARE_SHA256"), stream["boot_firmware_sha256"])
check("ABI_VERSION", constant("ABI_VERSION", 10), stream["abi_version"])
check("BOOTSTRAP_ADDRESS", constant("BOOTSTRAP_ADDRESS", 16), stream["bootstrap_address"])

# Every image must agree on the shared identity and bootstrap.
for image in ("continuous", "rx", "rx-stream"):
    other = manifest(image)
    for key in ("controller", "firmware", "rom_sha256", "abi_version", "bootstrap_address"):
        check(f"{image}.{key}", other[key], stream[key])
    assert other["runtime_install_required"], image
    assert other["bootstrap_requires_zero_reservation"], image

pointers = stream["pointer_installation"]
for name, key in (
    ("TRANSPORT_CONTEXT", "transport_context_pointer_address"),
    ("TRANSPORT_CALLBACK_OFFSET", "transport_callback_context_offset"),
    ("EXPECTED_TRANSPORT_CALLBACK", "expected_transport_callback"),
    ("RADIO_CALLBACK_TABLE", "radio_callback_table_pointer_address"),
    ("EXPECTED_RADIO_CALLBACK_TABLE", "expected_radio_callback_table"),
):
    check(name, constant(name, 16), pointers[key])
for name, key in (("PHASE_TABLE_SLOT", "phase_table_slot"), ("RX_TABLE_SLOT", "rx_table_slot")):
    check(name, constant(name, 10), pointers[key])

check("transport::HANDLE", constant("HANDLE", 16), stream["handle"])
check("transport::SDU_OCTETS", constant("SDU_OCTETS", 10), stream["sdu_octets"])
check("HCI_PACKET_TYPE", constant("HCI_PACKET_TYPE", 10), stream["transport"]["hci_packet_type"])

radio = stream["radio"]
for name, key, radix in (
    ("FREQUENCY_MHZ", "frequency_mhz", 10),
    ("HCI_TEST_CHANNEL", "hci_test_channel", 10),
    ("LOGICAL_CHANNEL", "logical_channel", 10),
    ("ACCESS_ADDRESS", "access_address", 16),
    ("CRC_INIT", "crc_init", 16),
    ("EXPECTED_RAW_HEADER", "expected_raw_header", 16),
):
    check(f"radio::{name}", constant(name, radix), radio[key])

for name, key in (
    ("RX_COMPLETE", "rx_complete"),
    ("CALLBACK_TABLE", "callback_table"),
    ("GUARD_BEFORE", "guard_before"),
    ("SNAPSHOT", "snapshot"),
    ("PAYLOAD", "payload"),
    ("GUARD_AFTER", "guard_after"),
    ("PHASE", "phase"),
    ("TRANSPORT", "transport"),
    ("TASK_STATE", "task_state"),
    ("REJECTED_SNAPSHOTS", "rejected_snapshots"),
    ("PHASE_TRACE", "phase_trace"),
    ("EMITTER", "emitter"),
    ("ISR_FORWARD", "isr_forward"),
):
    check(f"offsets::{name}", constant(name, 10), stream["resident_offsets"][key])

# Each image's allocator must be the one built for its reservation size, so a
# smaller reservation can never be installed under a larger image.
allocators = {}
for image in ("continuous", "rx", "rx-stream"):
    allocators[image] = (ROOT / "blobs" / image / "allocator.bin").read_bytes()
assert allocators["rx"] == allocators["rx-stream"], "equal reservations must share an allocator"
if allocators["continuous"] == allocators["rx"]:
    failures.append("continuous and rx allocators are identical despite differing reservations")
for image, data in allocators.items():
    if len(data) != 112:
        failures.append(f"{image} allocator is {len(data)} bytes, expected 112")
    expected = manifest(image)["files"]["allocator.bin"]["sha256"]
    import hashlib

    if hashlib.sha256(data).hexdigest() != expected:
        failures.append(f"{image} allocator does not match its manifest")

# Every image module must expose its own allocator rather than sharing one.
for module in ("continuous", "rx", "rx_stream"):
    pattern = rf"pub mod {module} \{{.*?ALLOCATOR: &\[u8; 112\] = include_bytes!\(\"\.\./blobs/([\w-]+)/allocator\.bin\"\)"
    match = re.search(pattern, source, re.S)
    if not match:
        failures.append(f"{module} does not include its own allocator")
    elif match[1].replace("-", "_") != module:
        failures.append(f"{module} includes the {match[1]} allocator")

# Allocation sizes are per image.
for image, module in (("continuous", "continuous"), ("rx", "rx"), ("rx-stream", "rx_stream")):
    expected = manifest(image)["files"]["native.bin"]["size"]
    match = re.search(
        rf"pub mod {module} \{{.*?pub const ALLOCATION_BYTES: u32 = (\d+);", source, re.S
    )
    assert match, f"{module}::ALLOCATION_BYTES missing"
    check(f"{module}::ALLOCATION_BYTES", int(match[1]), expected)

if failures:
    print("\n".join(failures), file=sys.stderr)
    sys.exit(1)
print(
    "ABI constants match all three manifests: identity, bootstrap, pointers, "
    "transport, radio, offsets and per-image allocation sizes."
)
